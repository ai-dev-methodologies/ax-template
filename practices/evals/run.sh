#!/usr/bin/env bash
# practices/evals/run.sh
# Advisory dashboard runner.
#
# Usage:  ./practices/evals/run.sh
#
# Reads   practices/rubric.yaml   — extracts axis names (advisory only)
# Calls   per-axis sub-scripts if they exist; emits N/A otherwise
# Writes  practices/evals/reports/YYYY-MM-DD.md
#
# EXIT BEHAVIOUR
#   Always exits 0.  This script is ADVISORY — it never gates merges.
#   Hard gates are: (a) spec_ref_guard.sh  (b) ./gradlew test{Domain}

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PRACTICES_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
RUBRIC="${PRACTICES_DIR}/rubric.yaml"
REPORTS_DIR="${SCRIPT_DIR}/reports"
REPORT_DATE="$(date +%F)"
REPORT_FILE="${REPORTS_DIR}/${REPORT_DATE}.md"

# ── Sanity checks ─────────────────────────────────────────────────────────────

if [[ ! -f "${RUBRIC}" ]]; then
  echo "[run.sh] ERROR: rubric.yaml not found at ${RUBRIC}" >&2
  exit 1
fi

mkdir -p "${REPORTS_DIR}"

# ── Axes (fixed per rubric.yaml v3) ──────────────────────────────────────────
# Parallel arrays: AXES, AXIS_SCRIPTS, AXIS_SCORES (bash 3-compatible)

AXES=(detection outcome reference portability drift)
AXIS_SCRIPTS=(
  "${SCRIPT_DIR}/cases/run.sh"
  "${SCRIPT_DIR}/outcome/run.sh"
  ""
  "${SCRIPT_DIR}/portability/run.sh"
  "${SCRIPT_DIR}/drift/run.sh"
)
AXIS_SCORES=("" "" "" "" "")

# ── Inline reference check ────────────────────────────────────────────────────

run_inline_reference() {
  local rules_dir="${PRACTICES_DIR}/rules"
  local total=0 missing=0 rule_file

  if [[ -d "${rules_dir}" ]]; then
    while IFS= read -r rule_file; do
      total=$(( total + 1 ))
      if ! grep -q '^spec_ref:' "${rule_file}" 2>/dev/null; then
        missing=$(( missing + 1 ))
      fi
    done < <(find "${rules_dir}" -name "*.md" ! -name "_*" 2>/dev/null)
  fi

  if [[ ${total} -eq 0 ]]; then
    echo "N/A (0 rules)"
  else
    local present=$(( total - missing ))
    echo "${present}/${total} rules have spec_ref"
  fi
}

# ── Run axes ──────────────────────────────────────────────────────────────────

i=0
while [[ ${i} -lt ${#AXES[@]} ]]; do
  axis="${AXES[${i}]}"
  script="${AXIS_SCRIPTS[${i}]}"

  if [[ "${axis}" == "reference" ]]; then
    AXIS_SCORES[${i}]="$(run_inline_reference)"
  elif [[ -n "${script}" && -x "${script}" ]]; then
    result="$("${script}" 2>&1)" && status=0 || status=$?
    if [[ ${status} -eq 0 ]]; then
      AXIS_SCORES[${i}]="${result:-PASS}"
    else
      AXIS_SCORES[${i}]="FAIL (exit ${status})"
    fi
  else
    AXIS_SCORES[${i}]="N/A"
  fi

  i=$(( i + 1 ))
done

# ── Compute advisory TOTAL ────────────────────────────────────────────────────

all_na=true
for score in "${AXIS_SCORES[@]}"; do
  if [[ "${score}" != "N/A"* ]]; then
    all_na=false
    break
  fi
done

if [[ "${all_na}" == "true" ]]; then
  TOTAL="N/A"
else
  TOTAL="see per-axis scores (weighted advisory sum not yet implemented)"
fi

# ── Rule count ────────────────────────────────────────────────────────────────

RULE_COUNT=0
if [[ -d "${PRACTICES_DIR}/rules" ]]; then
  RULE_COUNT=$(find "${PRACTICES_DIR}/rules" -name "*.md" ! -name "_*" 2>/dev/null | wc -l | tr -d ' ')
fi

# ── Write report ──────────────────────────────────────────────────────────────

{
  echo "# Practices Advisory Report — ${REPORT_DATE}"
  echo ""
  echo "> **Advisory only.** Scores are metrics, not merge gates."
  echo "> Hard gates: (a) \`spec_ref\` present, (b) \`./gradlew test{Domain}\` PASS."
  echo ""
  echo "## Summary"
  echo ""
  echo "| Field | Value |"
  echo "|-------|-------|"
  echo "| Date | ${REPORT_DATE} |"
  echo "| Rules | ${RULE_COUNT} |"
  echo "| TOTAL | ${TOTAL} |"
  echo ""
  echo "## Per-Axis Scores"
  echo ""
  echo "| Axis | Score |"
  echo "|------|-------|"
  j=0
  while [[ ${j} -lt ${#AXES[@]} ]]; do
    echo "| ${AXES[${j}]} | ${AXIS_SCORES[${j}]:-N/A} |"
    j=$(( j + 1 ))
  done
  echo ""
  echo "## Gating"
  echo ""
  echo "- \`binary_only: true\` (from rubric.yaml)"
  echo "- spec_ref guard: \`practices/evals/spec_ref_guard.sh\`"
  echo "- Gradle gate: \`./gradlew test{Domain}\`"
  echo ""
  echo "---"
  echo "_Generated by \`practices/evals/run.sh\`_"
} > "${REPORT_FILE}"

echo "[run.sh] Report written: ${REPORT_FILE}"
echo "[run.sh] TOTAL: ${TOTAL}"
